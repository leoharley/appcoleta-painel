            <h2>1. Quem somos</h2>
            <p>
                O <strong>AppColeta</strong> é uma plataforma de coleta de dados desenvolvida e operada pelo
                <strong>Instituto Alves Lima</strong>, com sede em Montes Claros - MG. Utilizamos aplicativo
                móvel para pesquisas de campo e um painel administrativo para gestão e análise das respostas.
            </p>

            <h2>2. Dados que coletamos</h2>

            <h3>2.1. Dados dos aplicadores (equipe de campo)</h3>
            <ul>
                <li>Nome completo, e-mail e nome de usuário para login</li>
                <li>Registros de acesso e atividade no aplicativo</li>
                <li>Localização geográfica no momento da aplicação (quando o questionário exige)</li>
            </ul>

            <h3>2.2. Dados fornecidos pelos respondentes</h3>
            <ul>
                <li>Respostas às perguntas do questionário</li>
                <li>Nome e contato (quando o questionário perguntar e o respondente consentir)</li>
                <li>Localização aproximada do local da entrevista (quando aplicável)</li>
                <li>Foto e áudio da entrevista (apenas se a pesquisa exigir <em>e</em> houver consentimento)</li>
            </ul>

            <div class="info-box">
                <strong><i class="fas fa-info-circle me-1"></i> Consentimento</strong><br>
                Nenhum dado pessoal do respondente é coletado sem que ele autorize expressamente no início da
                entrevista. O aplicador é orientado a explicar a finalidade da pesquisa antes de registrar
                qualquer resposta.
            </div>

            <h2>3. Como usamos os dados</h2>
            <ul>
                <li>Produzir relatórios agregados e análises estatísticas para o cliente contratante da pesquisa</li>
                <li>Garantir a rastreabilidade do trabalho de campo (quem, quando e onde aplicou)</li>
                <li>Aprimorar a qualidade das próximas pesquisas</li>
            </ul>
            <p>
                Dados individuais dos respondentes <strong>não são vendidos, cedidos ou compartilhados</strong>
                com terceiros fora do escopo da pesquisa contratada.
            </p>

            <h2>4. Compartilhamento com terceiros</h2>
            <p>
                Os dados podem ser processados por serviços auxiliares (hospedagem em nuvem, transcrição de
                áudio via IA) exclusivamente para viabilizar o funcionamento da plataforma. Esses provedores
                estão sujeitos a contratos que exigem confidencialidade e proteção dos dados.
            </p>

            <h2>5. Retenção e exclusão</h2>
            <p>
                As respostas ficam armazenadas pelo período necessário para conclusão do projeto de pesquisa,
                acrescido do prazo legal exigido para prestação de contas ao cliente contratante. Após esse
                prazo, os dados pessoais são anonimizados ou eliminados.
            </p>

            <h2>6. Seus direitos (LGPD)</h2>
            <p>Nos termos da Lei Geral de Proteção de Dados (Lei nº 13.709/2018), você tem direito a:</p>
            <ul>
                <li>Confirmar se tratamos dados sobre você</li>
                <li>Acessar seus dados</li>
                <li>Solicitar correção de dados incompletos ou incorretos</li>
                <li>Solicitar a eliminação de dados desnecessários ou tratados sem consentimento</li>
                <li>Revogar o consentimento a qualquer momento</li>
            </ul>
            <p>
                Para exercer qualquer um desses direitos, entre em contato pelos canais abaixo. Responderemos
                em até 15 dias úteis.
            </p>

            <h2>7. Segurança</h2>
            <p>
                Adotamos medidas técnicas e organizacionais para proteger os dados contra acesso não
                autorizado, perda ou alteração indevida: conexões criptografadas (HTTPS), controle de acesso
                por perfis, registros de auditoria e backups regulares.
            </p>

            <h2>8. Cookies</h2>
            <p>
                O painel administrativo utiliza cookies estritamente necessários para manter a sessão do
                usuário logado. Não utilizamos cookies para rastreamento publicitário.
            </p>

            <h2>9. Alterações desta política</h2>
            <p>
                Esta política pode ser atualizada quando houver mudanças na plataforma ou na legislação.
                Recomendamos consultar esta página periodicamente. A data no topo indica a versão vigente.
            </p>

