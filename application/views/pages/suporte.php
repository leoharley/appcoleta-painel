            <h2>Perguntas frequentes</h2>

            <details class="faq-item">
                <summary>Esqueci minha senha, como recupero?</summary>
                <div class="faq-body">
                    Solicite ao administrador do seu projeto que redefina sua senha pelo painel
                    (menu <strong>Equipe</strong> → botão de chave ao lado do seu usuário). Uma senha
                    provisória será gerada e você poderá alterá-la ao entrar.
                </div>
            </details>

            <details class="faq-item">
                <summary>O aplicativo não sincroniza. O que fazer?</summary>
                <div class="faq-body">
                    <ol>
                        <li>Confirme que o celular está com conexão de internet estável (Wi-Fi ou dados).</li>
                        <li>Abra o app e vá em <strong>Sincronização</strong> para forçar o envio.</li>
                        <li>Se as respostas estiverem marcadas como "pendentes" e não subirem, encerre o app,
                            abra de novo e tente sincronizar. Nenhum dado é perdido — fica salvo no aparelho.</li>
                        <li>Persistindo o problema, envie o log do app pelo WhatsApp acima informando seu usuário
                            e o horário aproximado da última tentativa.</li>
                    </ol>
                </div>
            </details>

            <details class="faq-item">
                <summary>Como exportar as respostas de uma pesquisa?</summary>
                <div class="faq-body">
                    No painel, entre em <strong>Respostas dos Formulários</strong>, aplique os filtros desejados
                    (questionário, período, aplicador) e clique em <strong>Exportar</strong> para gerar uma
                    planilha organizada, ou em <strong>Exportar Dados Brutos</strong> para o arquivo completo.
                </div>
            </details>

            <details class="faq-item">
                <summary>Como gero um relatório com gráficos?</summary>
                <div class="faq-body">
                    Acesse o menu <strong>Gráficos</strong>, selecione o questionário desejado e clique em
                    <strong>Gerar relatório</strong>. Uma nova aba abrirá com o relatório completo pronto para
                    ser impresso ou salvo em PDF (botão no topo da página).
                </div>
            </details>

            <details class="faq-item">
                <summary>Um aplicador foi desligado — como bloquear o acesso dele?</summary>
                <div class="faq-body">
                    No painel, vá em <strong>Equipe</strong>, encontre o usuário e clique no botão vermelho
                    para desativar. Ele não conseguirá mais fazer login nem sincronizar novas respostas. As
                    respostas já coletadas são preservadas.
                </div>
            </details>

            <details class="faq-item">
                <summary>Como criar um novo questionário?</summary>
                <div class="faq-body">
                    Entre em <strong>Campanhas</strong> → escolha o projeto → botão <strong>Novo
                    questionário</strong>. Preencha o título, as perguntas (texto simples, escolha única,
                    múltipla, data, número, foto) e as opções de resposta quando aplicável. Ative o
                    questionário para que ele apareça no app dos aplicadores.
                </div>
            </details>

            <details class="faq-item">
                <summary>É possível transcrever os áudios coletados?</summary>
                <div class="faq-body">
                    Sim. No menu <strong>Inteligência Artificial → Transcrições</strong>, clique em
                    <strong>Importar áudios das respostas</strong> para trazer os áudios anexados aos
                    formulários e depois em <strong>Transcrever pendentes</strong> para processar em lote via
                    IA. Os textos ficam disponíveis para edição.
                </div>
            </details>

            <details class="faq-item">
                <summary>Como configuro cotas por perfil (estratificação)?</summary>
                <div class="faq-body">
                    No painel, acesse <strong>Estratificação</strong>, escolha o questionário e defina as
                    dimensões (por pergunta, por aplicador ou por dia da semana) com as respectivas metas de
                    coleta. O progresso é acompanhado em tempo real conforme as respostas chegam.
                </div>
            </details>

            <details class="faq-item">
                <summary>Meus dados estão seguros?</summary>
                <div class="faq-body">
